"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path='../docs/assets/event-recovery-ex-core.js';
assert.ok(fs.existsSync(require('node:path').join(__dirname,path)), '연간·두 기준 비교 코어가 있어야 함');
const X=require(path);
const obs=[{openDt:'20190101',starPower:100},{openDt:'20191201',starPower:200},{openDt:'20200205',starPower:250},{openDt:'20210501',starPower:50},{openDt:'20230802',starPower:180},{openDt:'20230802',starPower:220},{openDt:'20230901',starPower:90}];
const a=X.compare(obs,'2020-02','20230802','20260903');
assert.equal(a.pre.mean,150);
assert.equal(a.interim.mean,50,'공개 월 작품 제외, 엄격한 사건 이후');
assert.equal(a.inclusiveInterim.mean,150,'월 포함 대안은 별도 표시');
assert.equal(a.first.mean,200,'동일 개봉일 모두 포함, 과거 평균에는 제외');
assert.equal(a.eventAnnual.sum,250);
assert.equal(a.returnAnnual.sum,490);
assert.equal(a.annualChange.ratio,1.96);
assert.equal(a.toPre.ratio,200/150);
assert.equal(a.toInterim.ratio,4);
assert.equal(a.post.mean,490/3);
const b=X.compare([{openDt:'20190101',starPower:100},{openDt:'20240101',starPower:200}],'2022-09','20240101','20260903');
assert.equal(b.eventAnnual.sum,null,'출연작 없음은 0점 아님');
assert.equal(b.interim.mean,null);
assert.equal(b.toInterim.ratio,null);
assert.equal(b.annualChange.ratio,null);
assert.equal(X.compare(obs,'2020-02',null,'20260903').interim.mean,null,'미복귀 사례에 가상의 복귀 전 평균을 만들지 않음');
assert.equal(X.pattern({preHawk:true,pause:true,returned:true,synergy:true,comparison:b}).status,'unknown');
assert.equal(X.pattern({preHawk:true,pause:true,returned:true,synergy:true,comparison:a}).status,'observed');
assert.equal(X.pattern({preHawk:true,pause:true,returned:true,synergy:false,comparison:a}).status,'not_observed');
assert.deepEqual(X.fraction(0,0),{n:0,d:0,percent:null});
console.log('event recovery EX comparisons: PASS');
