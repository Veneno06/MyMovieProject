const assert = require('node:assert/strict');
const H = require('../docs/assets/hawk-criterion-core.js');
const SP = require('../docs/assets/starpower-core.js');
const row = (id, score) => ({actorKey:`id:${id}`,id,name:'동명이인',score});
const year = (...rows) => new Map(rows.map(r=>[r.actorKey,r]));
const yearly = {2020:year(row('a',100),row('b',1)),2022:year(row('a',1),row('b',100)),2023:year(row('a',100),row('b',1))};
const states = H.annualStates(yearly,50,{includedYears:['2020','2022','2023']});
assert.equal(states['id:a'][2020],'Hawk');
assert.equal(states['id:b'][2020],'Dove');
assert.equal(states['id:a'][2021],'Unknown');
assert.deepEqual(H.transitions(states['id:a']),[{fromYear:2022,toYear:2023,from:'Dove',to:'Hawk'}]);
assert.equal(H.annualStates(yearly,50,{includedYears:['2020']})['id:a'][2022],'Unknown');
const f = H.persistentHawksFdr(yearly,50,.05);
assert.equal(f.significant.length,0);
assert.ok(f.tests.every(x=>Number.isFinite(x.qValue)&&x.qValue>=x.pValue));
assert.equal(states['id:a'][2020],'Hawk','annual candidate need not be persistent');
const adjusted = H.adjustedPValues([{pValue:.01},{pValue:.04},{pValue:.03},{pValue:.9}]);
assert.deepEqual(adjusted.map(x=>x.qValue),[.04,.05333333333333334,.05333333333333334,.9]);
const movies = ['20180101','20200101','20210615','20220101'].map((date,i)=>({movieCd:String(i),movieNm:String(i),openDt:date,nation:'한국',audiAcc:100,actors:[{id:'a',name:'A'}]}));
const pre = H.buildPreEventAnalysis(SP,movies,{eventDate:'2021-06-15',windowMode:'trailing',windowYears:2});
assert.equal(pre.eventDate,'2021-06-15');
assert.equal(pre.cutoffDate,'20210614');
assert.ok(pre.model.observations.every(o=>o.openDt<'20210615'));
assert.deepEqual(Object.keys(pre.yearly),['2020']);
assert.throws(()=>H.buildPreEventAnalysis(SP,movies,{eventDate:'2021-02-30'}));
console.log('Hawk core regression tests passed');
